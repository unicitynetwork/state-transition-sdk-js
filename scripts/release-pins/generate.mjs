#!/usr/bin/env node
// Release pin generator (owner §45, design briefs/utb-cache-design.md "Implementation and release artifacts").
//
// Input: release-pins/manifest.json (reviewed by hand) and the binary source bundles it names. Output:
// src/api/bft/trustbase/ReleasePins.generated.ts, the rows of RELEASE_PINS.
//
// Before it writes anything it verifies, independently of the manifest, every bundle: canonical encoding (decode and re-encode give the same
// bytes), the network, every signature and link of the history (VerifiedReleasePin.verify), the genesis and tip entry ids and epochs, and the
// SHA-256 of the file. Every derived value must equal the one written in the manifest; a mismatch is an error, the manifest is never rewritten.
//
//   node scripts/release-pins/generate.mjs           write the generated file
//   node scripts/release-pins/generate.mjs --check   verify; fail if the generated file differs from what would be written
//   node scripts/release-pins/generate.mjs --derive  print the derived rows as JSON (to author or review a manifest entry)
//
// Build first (`npm run build`): it imports ../../lib. The manifest is shared byte for byte with sdk-rust.
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const OUT = resolve(root, 'src/api/bft/trustbase/ReleasePins.generated.ts');
const lib = (path) => import(`../../lib/${path}`);

const hex = (bytes) => Buffer.from(bytes).toString('hex');
const same = (a, b) => Buffer.compare(Buffer.from(a), Buffer.from(b)) === 0;

async function derive(entry) {
  const { releasePinFromBundle, VerifiedReleasePin, TRUST_BASE_BUNDLE_LIMITS } = await lib(
    'api/bft/trustbase/ReleasePin.js',
  );
  const { TrustBaseBundle } = await lib('api/bft/trustbase/TrustBaseBundle.js');
  const bytes = new Uint8Array(readFileSync(resolve(root, 'release-pins', entry.bundle)));
  const pin = await releasePinFromBundle(bytes);
  const bundle = await TrustBaseBundle.decode(bytes, TRUST_BASE_BUNDLE_LIMITS);
  if (!same(await TrustBaseBundle.encode(bundle.entries), bytes)) {
    throw new Error(`${entry.name}: the bundle is not in canonical encoding.`);
  }
  await VerifiedReleasePin.verify(pin);
  if (createHash('sha256').update(bytes).digest('hex') !== hex(pin.bundleSha256)) {
    throw new Error(`${entry.name}: digest.`);
  }
  return {
    bundle: entry.bundle,
    bundleSha256: hex(pin.bundleSha256),
    genesisEntryId: hex(pin.genesisEntryId),
    genesisEpoch: pin.genesisEpoch.toString(),
    name: entry.name,
    networkId: pin.networkId.id,
    pinnedEntryId: hex(pin.pinnedEntryId),
    pinnedEpoch: pin.pinnedEpoch.toString(),
    _bytes: bytes,
  };
}

function render(manifest, rows) {
  const lines = [
    '// GENERATED by scripts/release-pins/generate.mjs from release-pins/manifest.json. Do not edit: CI regenerates it and fails on any difference.',
    `// Source: ${manifest.source.repository}#${manifest.source.pullRequest} at ${manifest.source.commit}.`,
    '',
    '/** One row of the release table as plain data; ReleasePin.ts turns it into {@link IReleasePin}. */',
    'export interface IReleasePinRow {',
    '  readonly bundleHex: string;',
    '  readonly bundleSha256: string;',
    '  readonly genesisEntryId: string;',
    '  readonly genesisEpoch: string;',
    '  readonly name: string;',
    '  readonly networkId: number;',
    '  readonly pinnedEntryId: string;',
    '  readonly pinnedEpoch: string;',
    '}',
    '',
    'export const RELEASE_PIN_ROWS: readonly IReleasePinRow[] = [',
  ];
  for (const row of rows) {
    lines.push(
      '  {',
      '    bundleHex:',
      `      '${hex(row._bytes)}',`,
      `    bundleSha256: '${row.bundleSha256}',`,
      `    genesisEntryId: '${row.genesisEntryId}',`,
      `    genesisEpoch: '${row.genesisEpoch}',`,
      `    name: '${row.name}',`,
      `    networkId: ${row.networkId},`,
      `    pinnedEntryId: '${row.pinnedEntryId}',`,
      `    pinnedEpoch: '${row.pinnedEpoch}',`,
      '  },',
    );
  }
  lines.push('];', '');
  return lines.join('\n');
}

const mode = process.argv[2] ?? '';
const manifestText = readFileSync(resolve(root, 'release-pins/manifest.json'), 'utf8');
const manifest = JSON.parse(manifestText);
// The manifest is shared byte for byte with sdk-rust: keys sorted, 2-space indent, trailing newline.
const sorted = (value) =>
  Array.isArray(value)
    ? value.map(sorted)
    : value !== null && typeof value === 'object'
      ? Object.fromEntries(
          Object.keys(value)
            .sort()
            .map((key) => [key, sorted(value[key])]),
        )
      : value;
if (`${JSON.stringify(sorted(manifest), null, 2)}\n` !== manifestText) {
  throw new Error(
    'release-pins/manifest.json is not in canonical form (sorted keys, 2-space indent, trailing newline).',
  );
}
const expectedFiles = ['manifest.json', ...manifest.networks.map((entry) => entry.bundle)].sort();
const actualFiles = readdirSync(resolve(root, 'release-pins')).sort();
if (JSON.stringify(expectedFiles) !== JSON.stringify(actualFiles)) {
  throw new Error(`release-pins/ holds ${actualFiles.join(', ')}; the manifest names ${expectedFiles.join(', ')}.`);
}
if (mode === '--derive') {
  const rows = [];
  for (const entry of manifest.networks) {
    const { _bytes, ...row } = await derive(entry);
    rows.push(row);
  }
  console.log(JSON.stringify(rows, null, 2));
  process.exit(0);
}
const rows = [];
for (const entry of manifest.networks) {
  const row = await derive(entry);
  for (const key of ['bundleSha256', 'genesisEntryId', 'genesisEpoch', 'networkId', 'pinnedEntryId', 'pinnedEpoch']) {
    if (entry[key] !== row[key]) {
      throw new Error(`${entry.name}: manifest ${key} ${entry[key]} differs from the bundle's ${row[key]}.`);
    }
  }
  rows.push(row);
}
const names = new Set(rows.map((row) => row.name));
const ids = new Set(rows.map((row) => row.networkId));
if (names.size !== rows.length || ids.size !== rows.length) {
  throw new Error('Duplicate network name or id in the manifest.');
}
const text = render(manifest, rows);
if (mode === '--check') {
  if (readFileSync(OUT, 'utf8') !== text) {
    console.error(
      'ReleasePins.generated.ts differs from what the manifest and bundles generate; run scripts/release-pins/generate.mjs.',
    );
    process.exit(1);
  }
  console.log(
    `release pins OK: ${rows.map((row) => `${row.name} (network ${row.networkId}, epoch ${row.pinnedEpoch})`).join(', ')}`,
  );
} else if (mode === '') {
  writeFileSync(OUT, text);
  console.log(`wrote ${OUT}`);
} else {
  throw new Error(`Unknown option ${mode}.`);
}
