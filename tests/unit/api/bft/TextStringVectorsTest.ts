import { readFileSync } from 'node:fs';
import path from 'node:path';

import { RootTrustBaseV2 } from '../../../../src/api/bft/trustbase/RootTrustBaseV2.js';
import { TrustBaseHistory } from '../../../../src/api/bft/trustbase/TrustBaseHistory.js';
import { UnicitySeal } from '../../../../src/api/bft/UnicitySeal.js';
import { UnicitySealQuorumSignaturesVerificationRule } from '../../../../src/api/bft/verification/rule/UnicitySealQuorumSignaturesVerificationRule.js';
import { SealVerificationSession } from '../../../../src/api/bft/verification/SealVerificationSession.js';
import { Secp256k1SignatureVerifier } from '../../../../src/crypto/secp256k1/Secp256k1SignatureVerifier.js';
import { CborDeserializer } from '../../../../src/serialization/cbor/CborDeserializer.js';
import { CborError } from '../../../../src/serialization/cbor/CborError.js';
import { CborSerializer } from '../../../../src/serialization/cbor/CborSerializer.js';
import { HexConverter } from '../../../../src/util/HexConverter.js';
import { VerificationStatus } from '../../../../src/verification/VerificationStatus.js';

interface ITextVectors {
  committee: { entryId: string; hex: string; memberIdsHex: string[] };
  decode: { hex: string; name: string; reencodesIdentically?: boolean; valid: boolean }[];
  seals: { hex: string; name: string; signers: string[]; valid: boolean }[];
}

const VECTORS = JSON.parse(
  readFileSync(path.join(__dirname, '../../../vectors/text-string/vectors.json'), 'utf8'),
) as ITextVectors;
const utf8 = (hex: string): Uint8Array => HexConverter.decode(hex);
const textOf = (bytes: Uint8Array): Uint8Array =>
  CborSerializer.encodeTextString(new TextDecoder('utf-8', { ignoreBOM: true }).decode(bytes));

describe('CBOR text strings decode byte for byte (shared vectors, generated by Go)', () => {
  it('keeps a leading U+FEFF and refuses invalid UTF-8', () => {
    const bom = utf8('efbbbf612d62');
    expect(Array.from(new TextEncoder().encode(CborDeserializer.decodeTextString(textOf(bom))))).toEqual(
      Array.from(bom),
    );
    expect(() => CborDeserializer.decodeTextString(new Uint8Array([0x62, 0xff, 0x61]))).toThrow(CborError);
  });

  it.each(VECTORS.decode)('decode $name', ({ hex, valid, reencodesIdentically }) => {
    if (!valid) {
      expect(() => RootTrustBaseV2.decode(HexConverter.decode(hex))).toThrow();
      return;
    }
    const entry = RootTrustBaseV2.decode(HexConverter.decode(hex));
    expect(entry.members.map((m) => HexConverter.encode(new TextEncoder().encode(m.nodeId)))).toEqual(
      VECTORS.committee.memberIdsHex,
    );
    if (reencodesIdentically) {
      expect(HexConverter.encode(entry.encode())).toEqual(hex);
    }
  });

  it('the committee entry has the Go EntryID', async () => {
    expect(
      HexConverter.encode(await RootTrustBaseV2.decode(HexConverter.decode(VECTORS.committee.hex)).entryId()),
    ).toEqual(VECTORS.committee.entryId);
  });

  it.each(VECTORS.seals)('seal $name', async ({ hex, signers, valid }) => {
    const seal = UnicitySeal.fromCBOR(HexConverter.decode(hex));
    expect(
      [...(seal.signatures ?? new Map<string, Uint8Array>()).keys()]
        .map((k) => HexConverter.encode(new TextEncoder().encode(k)))
        .sort(),
    ).toEqual([...signers].sort());
    const history = TrustBaseHistory.create(HexConverter.decode(VECTORS.committee.entryId));
    await history.append(RootTrustBaseV2.decode(HexConverter.decode(VECTORS.committee.hex)));
    const session = new SealVerificationSession(
      history,
      new UnicitySealQuorumSignaturesVerificationRule(new Secp256k1SignatureVerifier()),
    );
    expect((await session.authenticate(seal)).status).toEqual(valid ? VerificationStatus.OK : VerificationStatus.FAIL);
  });
});
